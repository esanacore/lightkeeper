"""Render the bedside enclosure's documentation images and export its STLs.

1. Writes hardware/enclosure/screen_in_range.scad: the real Lightkeeper screen
   (the in_range_flat vector) as runs of ink pixels, from the same rasterizer
   the Pi uses, so the CAD renders show exactly what the panel will show.
2. If OpenSCAD is installed, renders PNGs into hardware/enclosure/renders/ and
   exports printable STLs into hardware/enclosure/stl/.
3. Writes hardware/enclosure/manifest.json with the SHA-256 of every input, so
   tests/test_enclosure.py fails when the model changes without a re-render.

Usage (from the repo root):
    python tools/render_enclosure.py            # everything
    python tools/render_enclosure.py --screen   # only the screen include (no OpenSCAD needed)

Rendering needs OpenSCAD (https://openscad.org) on PATH or in its default
Windows location, and Pillow to downsample the images (anti-aliasing).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from lightkeeper.infrastructure.epaper_bitmap import render_bitmap  # noqa: E402

ENCLOSURE = ROOT / "hardware" / "enclosure"
MODEL = ENCLOSURE / "bedside.scad"
SCREEN = ENCLOSURE / "screen_in_range.scad"
MANIFEST = ENCLOSURE / "manifest.json"
VECTOR = "in_range_flat"

# name: (part, eye xyz, center xyz, description)
VIEWS = {
    "hero": (
        "assembly",
        (-150, 230, 115),
        (0, -14, -6),
        "Standing at its 15 degree lean, front three-quarter",
    ),
    "front": ("assembly", (0, 290, 30), (0, -14, -4), "Front, at reading height"),
    "back": (
        "assembly",
        (150, -240, 120),
        (0, -14, -6),
        "Rear three-quarter: cable notch, vents, plinth",
    ),
    "side": ("assembly", (-300, -14, 5), (0, -14, -4), "Side: the plinth and the lean angle"),
    "exploded": (
        "exploded",
        (-260, 210, 140),
        (0, -10, 0),
        "Exploded: bezel, glass, HAT, Pi, back cover",
    ),
    "exploded_back": (
        "exploded",
        (230, -230, 120),
        (0, -10, 0),
        "Exploded from behind: the Pi on the HAT header",
    ),
}
STLS = {"bezel": "bedside-bezel.stl", "back": "bedside-back.stl"}
SIZE = (1600, 1100)
SUPERSAMPLE = 2


def screen_runs(lines: list[str]) -> list[tuple[int, int, int]]:
    """(row, first column, length) for every horizontal run of ink pixels."""
    bitmap = render_bitmap(lines)
    runs = []
    for y in range(bitmap.height):
        x = 0
        while x < bitmap.width:
            if bitmap.is_ink(x, y):
                start = x
                while x < bitmap.width and bitmap.is_ink(x, y):
                    x += 1
                runs.append((y, start, x - start))
            else:
                x += 1
    return runs


def screen_include() -> str:
    """Return the OpenSCAD include that draws the in-range screen."""
    vectors = json.loads((ROOT / "spec" / "display_vectors.json").read_text(encoding="utf-8"))
    lines = next(c["lines"] for c in vectors["cases"] if c["name"] == VECTOR)
    runs = screen_runs(lines)
    body = ",\n  ".join(f"[{r}, {c}, {n}]" for r, c, n in runs)
    return (
        "// Generated by tools/render_enclosure.py from the rasterizer and the\n"
        f"// {VECTOR} vector ({' / '.join(lines)}). Do not edit.\n"
        f"SCREEN_RUNS = [\n  {body}\n];\n"
    )


def sha256(path: Path) -> str:
    """Hex digest of a file, ignoring line-ending differences."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def manifest() -> dict[str, object]:
    """Hashes of the inputs the renders and STLs were made from."""
    return {
        "inputs": {p.name: sha256(p) for p in (MODEL, SCREEN)},
        "renders": {name: f"renders/{name}.png" for name in VIEWS},
        "stls": {part: f"stl/{name}" for part, name in STLS.items()},
    }


def find_openscad() -> str | None:
    """OpenSCAD's command-line executable, if installed."""
    found = shutil.which("openscad")
    if found:
        return found
    default = Path("C:/Program Files/OpenSCAD/openscad.com")
    return str(default) if default.exists() else None


def run(openscad: str, *args: str) -> None:
    """Run OpenSCAD on the model and fail loudly on error."""
    result = subprocess.run(  # noqa: S603 (fixed arguments built here)
        [openscad, *args, str(MODEL)], capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        raise SystemExit(f"openscad failed: {' '.join(args)}\n{result.stderr}")


def ascii_stl_to_binary(path: Path) -> None:
    """Rewrite an ASCII STL as binary STL: about a fifth of the size, read by every slicer."""
    import struct

    facets = []
    normal: list[float] = []
    vertices: list[float] = []
    for line in path.read_text(encoding="ascii").splitlines():
        words = line.split()
        if words[:2] == ["facet", "normal"]:
            normal = [float(v) for v in words[2:5]]
            vertices = []
        elif words[:1] == ["vertex"]:
            vertices += [float(v) for v in words[1:4]]
        elif words[:1] == ["endfacet"]:
            facets.append(struct.pack("<12fH", *normal, *vertices, 0))
    header = b"Lightkeeper bedside enclosure (tools/render_enclosure.py)".ljust(80, b" ")
    path.write_bytes(header + struct.pack("<I", len(facets)) + b"".join(facets))


def render_all(openscad: str) -> None:
    """Render every view and export every STL."""
    from PIL import Image  # optional dependency for local rendering only

    (ENCLOSURE / "renders").mkdir(exist_ok=True)
    (ENCLOSURE / "stl").mkdir(exist_ok=True)
    width, height = (s * SUPERSAMPLE for s in SIZE)
    for name, (part, eye, center, _) in VIEWS.items():
        out = ENCLOSURE / "renders" / f"{name}.png"
        camera = ",".join(str(v) for v in (*eye, *center))
        run(
            openscad,
            "-o",
            str(out),
            "-D",
            f'part="{part}"',
            f"--imgsize={width},{height}",
            f"--camera={camera}",
            "--projection=p",
            "--colorscheme=Tomorrow",
        )
        with Image.open(out) as image:
            image.resize(SIZE, Image.LANCZOS).save(out, optimize=True)
        print(f"rendered {out.relative_to(ROOT)}")
    for part, name in STLS.items():
        out = ENCLOSURE / "stl" / name
        run(openscad, "-o", str(out), "-D", f'part="{part}"')
        ascii_stl_to_binary(out)
        print(f"exported {out.relative_to(ROOT)}")


def main(argv: list[str] | None = None) -> int:
    """Write the screen include, then render if OpenSCAD is available."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--screen", action="store_true", help="only write the screen include")
    args = parser.parse_args(argv)
    SCREEN.write_text(screen_include(), encoding="utf-8", newline="\n")
    print(f"wrote {SCREEN.relative_to(ROOT)}")
    if args.screen:
        return 0
    openscad = find_openscad()
    if openscad is None:
        print("OpenSCAD not found: install it to render images and STLs", file=sys.stderr)
        return 1
    render_all(openscad)
    MANIFEST.write_text(json.dumps(manifest(), indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
