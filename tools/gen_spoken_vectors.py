"""Generate spec/spoken_vectors.json: the spoken sentence for every display vector.

Each case in spec/display_vectors.json is run through the same rules the
tests use (parse every entry, classify the newest survivor at the shared
fixed clock, with the case's thresholds and fetch error), then through
`spoken_text`. The Python tests (tests/test_spoken.py) and the Swift
package (SpokenVectorTests) both check every sentence in the file, so the
spoken form stays identical across implementations (FR-017).

Usage (from the repo root):
    python tools/gen_spoken_vectors.py           # rewrite spec/spoken_vectors.json
    python tools/gen_spoken_vectors.py --check   # report drift; exit 1 if any
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from lightkeeper.application.spoken import spoken_text  # noqa: E402
from lightkeeper.domain.glucose import parse_entries  # noqa: E402
from lightkeeper.domain.status import Status, Thresholds, classify  # noqa: E402

DISPLAY_VECTORS = ROOT / "spec" / "display_vectors.json"
SPOKEN_VECTORS = ROOT / "spec" / "spoken_vectors.json"

# The fixed clock every vector is dated against (tests/helpers.py NOW).
NOW = datetime(2026, 10, 18, 12, 0, tzinfo=UTC)

DESCRIPTION = (
    "The spoken form of every case in spec/display_vectors.json, for screen readers: "
    "one sentence per vector name, generated by tools/gen_spoken_vectors.py and checked "
    "by the Python and Swift test suites. Do not edit by hand. It is built from the "
    "classified status, never from the rendered lines, and it is never more current than "
    "the screen: the age is always spoken, STALE speaks its warning first with no trend "
    "word, and NO DATA never speaks a number. 'Nightscout unreachable.' is added when the "
    "fetch failed. For polite or passive accessibility channels only; it is not published "
    "to Home Assistant or any text-to-speech path."
)


def age(item: dict[str, Any]) -> timedelta:
    """Return an entry's age, from `minutes_ago` or `seconds_ago` (exactly one is given)."""
    if "seconds_ago" in item:
        return timedelta(seconds=item["seconds_ago"])
    return timedelta(minutes=item["minutes_ago"])


def raw_entries(case: dict[str, Any]) -> list[dict[str, Any]]:
    """Return every raw entry in the case, dated relative to NOW."""
    items = case["entries"] if "entries" in case else [case]
    raws = []
    for item in items:
        if item["entry"] is not None:
            raw = dict(item["entry"])
            raw["date"] = int((NOW - age(item)).timestamp() * 1000)
            raws.append(raw)
    return raws


def thresholds(case: dict[str, Any]) -> Thresholds:
    """Return the case's custom thresholds, or the defaults."""
    custom = case.get("thresholds")
    if custom is None:
        return Thresholds()
    return Thresholds(
        urgent_low=custom["urgent_low"],
        low=custom["low"],
        high=custom["high"],
        urgent_high=custom["urgent_high"],
        stale_after=timedelta(minutes=custom["stale_after_minutes"]),
    )


def status_for(case: dict[str, Any]) -> Status:
    """Classify the newest trustworthy entry of a case, as every display does."""
    readings = parse_entries(raw_entries(case))
    return classify(readings[0] if readings else None, NOW, thresholds(case))


def build(display_vectors: Path = DISPLAY_VECTORS) -> dict[str, Any]:
    """Return the spoken spec for every display vector, in the display file's order."""
    cases = json.loads(display_vectors.read_text(encoding="utf-8"))["cases"]
    return {
        "description": DESCRIPTION,
        "cases": {case["name"]: spoken_text(status_for(case), case["error"]) for case in cases},
    }


def render(spec: dict[str, Any]) -> str:
    """Return the file's exact text: two-space JSON with a trailing newline."""
    return json.dumps(spec, indent=2, ensure_ascii=False) + "\n"


def drift(expected: dict[str, Any], path: Path) -> list[str]:
    """List each way the file at `path` differs from `expected`, one line apiece."""
    if not path.exists():
        return [f"{path.name} is missing"]
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    try:
        actual = json.loads(text)
    except ValueError as exc:
        return [f"{path.name} is not valid JSON: {exc}"]
    if not isinstance(actual, dict) or not isinstance(actual.get("cases"), dict):
        return [f"{path.name} has no 'cases' object"]
    problems = []
    if actual.get("description") != expected["description"]:
        problems.append("description differs")
    if set(actual) != set(expected):
        problems.append(f"top-level keys are {sorted(actual)}, expected {sorted(expected)}")
    want, have = expected["cases"], actual["cases"]
    for name in want:
        if name not in have:
            problems.append(f"{name}: missing")
        elif have[name] != want[name]:
            problems.append(f"{name}: {have[name]!r} should be {want[name]!r}")
    problems += [f"{name}: not a display vector" for name in have if name not in want]
    if not problems and list(have) != list(want):
        problems.append("cases are not in spec/display_vectors.json order")
    if not problems and text != render(expected):
        problems.append("formatting differs; regenerate the file")
    return problems


def main(argv: list[str] | None = None) -> int:
    """Write the spoken spec, or with --check report how the committed one drifted."""
    parser = argparse.ArgumentParser(description="Generate spec/spoken_vectors.json.")
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    parser.add_argument("--display", type=Path, default=DISPLAY_VECTORS, help=argparse.SUPPRESS)
    parser.add_argument("--spoken", type=Path, default=SPOKEN_VECTORS, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    expected = build(args.display)
    if args.check:
        problems = drift(expected, args.spoken)
        for problem in problems:
            print(f"drift: {problem}", file=sys.stderr)
        if problems:
            print("run: python tools/gen_spoken_vectors.py", file=sys.stderr)
            return 1
        print(f"{args.spoken.name} is up to date ({len(expected['cases'])} cases)")
        return 0
    with args.spoken.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(expected))
    print(f"wrote {args.spoken.name} ({len(expected['cases'])} cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
