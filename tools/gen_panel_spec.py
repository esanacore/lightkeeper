"""Generate the shared panel specs: the Keeper 5x8 font and the pixel vectors.

Writes two files from the Python reference rasterizer:

- spec/font5x8.json: every glyph of the project's own font (font5x7.py).
- spec/panel_vectors.json: every display vector drawn at every panel
  profile (plus a few stamped cases), each pinned by the CRC-32 of its packed
  rows and its ink count. The JavaScript and C++ ports must reproduce every
  case exactly, so one integer-only layout draws the same pixels everywhere.

tests/test_panel_vectors.py fails if either committed file differs from what
this script produces.

Usage (from the repo root):
    python tools/gen_panel_spec.py           # write both files
    python tools/gen_panel_spec.py --check   # exit 1 if either is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from lightkeeper.infrastructure import panel_layout as layout  # noqa: E402
from lightkeeper.infrastructure.epaper_bitmap import render_bitmap  # noqa: E402
from lightkeeper.infrastructure.font5x7 import (  # noqa: E402
    FALLBACK,
    GLYPH_HEIGHT,
    GLYPH_WIDTH,
    glyph_table,
)
from lightkeeper.infrastructure.panel_profiles import (  # noqa: E402
    ALIASES,
    DEFAULT_PROFILE,
    PROFILES,
)

DISPLAY_VECTORS = Path("spec") / "display_vectors.json"
FONT = Path("spec") / "font5x8.json"
PANEL_VECTORS = Path("spec") / "panel_vectors.json"
PANEL_SPEC_VERSION = 1

# (vector, profile, stamp): an age-row stamp, a bottom-strip stamp, and a
# larger stamp on a tall panel.
STAMPED = [
    ("in_range_flat", "waveshare_2in9", "02:14"),
    ("no_data_unreachable", "waveshare_2in9", "23:59"),
    ("stale_at_16_minutes", "kindle", "00:00"),
]

DESCRIPTION = (
    "Shared pixel vectors for the 1-bit e-paper panel. Every case in "
    "spec/display_vectors.json is drawn at every profile (and a few cases with a stamp) by "
    "the Python reference rasterizer (src/lightkeeper/infrastructure/panel_layout.py and "
    "epaper_bitmap.py), and pinned by the CRC-32 of its packed rows and its count of ink "
    "pixels. The JavaScript and C++ ports must match every case. Generated by "
    "tools/gen_panel_spec.py; do not edit. panel_spec_version increments whenever an "
    "existing case's pixels change; adding a case or a profile does not bump it."
)

HASH = {
    "algorithm": "CRC-32 as zlib.crc32 computes it (CRC-32/ISO-HDLC: reflected polynomial "
    "0xEDB88320, initial value and final XOR 0xFFFFFFFF); the CRC-32 of the ASCII bytes "
    "'123456789' is 3421780262 (0xCBF43926)",
    "input": "the packed rows of the landscape image, top row first",
    "row": "ceil(width / 8) bytes; 1 = ink, 0 = paper; the leftmost pixel is the most "
    "significant bit of the first byte; padding bits after the last pixel are 0",
    "ink": "the number of ink pixels in the image",
}

# The layout, in order, for porters. The code is the definition; this text
# names every rule a port has to reproduce.
