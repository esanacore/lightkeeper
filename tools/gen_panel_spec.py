def font_spec() -> dict[str, object]:
    """Return the font as data."""
    return {
        "name": "Keeper 5x8",
        "description": "The project's own bitmap font (src/lightkeeper/infrastructure/"
        "font5x7.py), for printable ASCII. Each glyph is eight rows of five cells, top to "
        "bottom; '#' is ink and '.' is paper. Capitals and digits use the top seven rows "
        "(the baseline is under row 6); row 7 holds descenders. Any character not listed "
        "draws as the fallback. Generated by tools/gen_panel_spec.py; do not edit.",
        "glyph_width": GLYPH_WIDTH,
        "glyph_height": GLYPH_HEIGHT,
        "fallback": FALLBACK,
        "glyphs": {char: list(rows) for char, rows in glyph_table().items()},
    }


def panel_spec() -> dict[str, object]:
    """Every vector at every profile, plus the stamped cases."""
    vectors = json.loads((ROOT / DISPLAY_VECTORS).read_text(encoding="utf-8"))["cases"]
    by_name = {case["name"]: case for case in vectors}
    cases = []
    for profile in PROFILES.values():
        for case in vectors:
            cases.append(_case(case["name"], case["lines"], profile.name, None))
    for name, profile_name, stamp in STAMPED:
        cases.append(_case(name, by_name[name]["lines"], profile_name, stamp))
    return {
        "panel_spec_version": PANEL_SPEC_VERSION,
        "description": DESCRIPTION,
        "font": FONT.as_posix(),
        "hash": HASH,
        "layout": {
            "constants": {
                "band_pad": layout.BAND_PAD,
                "rule_thickness": layout.RULE_THICKNESS,
                "hatch_width": layout.HATCH_WIDTH,
                "hatch_pitch": layout.HATCH_PITCH,
                "dash_width": layout.DASH_WIDTH,
                "dash_on": layout.DASH_ON,
                "dash_off": layout.DASH_OFF,
                "min_gap": layout.MIN_GAP,
                "readable_scale": layout.READABLE_SCALE,
                "reserved_body_lines": layout.RESERVED_BODY_LINES,
                "stamp_min_scale": layout.STAMP_MIN_SCALE,
                "reference_headline": layout.REFERENCE_HEADLINE,
            },
            "rules": RULES,
        },
        "treatments": layout.TREATMENTS,
        "unknown_treatment": layout.UNKNOWN_TREATMENT,
        "default_profile": DEFAULT_PROFILE,
        "profiles": {
            p.name: {"width": p.width, "height": p.height, "description": p.description}
            for p in PROFILES.values()
        },
        "aliases": ALIASES,
        "cases": cases,
    }


def _case(name: str, lines: list[str], profile: str, stamp: str | None) -> dict[str, object]:
    size = PROFILES[profile]
    bitmap = render_bitmap(lines, size.width, size.height, stamp)
    case: dict[str, object] = {
        "vector": name,
        "profile": profile,
        "width": size.width,
        "height": size.height,
        "lines": lines,
    }
    if stamp is not None:
        case["stamp"] = stamp
    case["crc32"] = zlib.crc32(bitmap.to_packed_rows())
    case["ink"] = sum(bitmap.ink)
    return case


def dump_font(spec: dict[str, object]) -> str:
    """JSON text with one glyph per line."""
    glyphs = spec["glyphs"]
    assert isinstance(glyphs, dict)
    head = json.dumps({k: v for k, v in spec.items() if k != "glyphs"}, indent=2)
    rows = ",\n".join(f"    {json.dumps(char)}: {json.dumps(g)}" for char, g in glyphs.items())
    return head[:-2] + ',\n  "glyphs": {\n' + rows + "\n  }\n}\n"


def dump_panel(spec: dict[str, object]) -> str:
    """JSON text with one case per line, so a diff shows exactly which cases moved."""
    cases = spec["cases"]
    assert isinstance(cases, list)
    head = json.dumps({k: v for k, v in spec.items() if k != "cases"}, indent=2)
    rows = ",\n".join(f"    {json.dumps(case)}" for case in cases)
    return head[:-2] + ',\n  "cases": [\n' + rows + "\n  ]\n}\n"


def build() -> dict[Path, str]:
    """Return the text of each generated file, by path relative to the repo root."""
    return {FONT: dump_font(font_spec()), PANEL_VECTORS: dump_panel(panel_spec())}


def main(argv: list[str] | None = None) -> int:
    """Write the specs, or with --check report whether they are current."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a file is out of date")
    args = parser.parse_args(argv)
    stale = []
    for relative, text in build().items():
        path = ROOT / relative
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""
        if current == text:
            continue
        stale.append(relative.as_posix())
        if not args.check:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {relative.as_posix()}")
    if args.check and stale:
        print(f"out of date: {', '.join(stale)}; run python tools/gen_panel_spec.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
