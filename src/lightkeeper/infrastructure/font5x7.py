# Anything outside printable ASCII draws as "?", never as a blank that could
# hide a character; the renderers only emit ASCII, so this is a safety net.
FALLBACK = "?"


def glyph(char: str) -> tuple[str, ...]:
    """Return the eight rows for `char`, or the fallback glyph."""
    return _GLYPHS.get(char, _GLYPHS[FALLBACK])


def covered() -> frozenset[str]:
    """Every character with its own glyph."""
    return frozenset(_GLYPHS)
